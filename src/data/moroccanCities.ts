const normalizeStr = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();

export const searchMoroccanCities = (query: string, limit = 8): string[] => {
  if (!query || query.trim() === "") {
    return POPULAR_CITIES.slice(0, limit);
  }
  const cleanQ = normalizeStr(query);
  return MOROCCAN_CITIES.filter((city) => normalizeStr(city).includes(cleanQ)).slice(0, limit);
};
